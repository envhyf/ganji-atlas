import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const load=async file=>import(`data:text/javascript;base64,${Buffer.from(await readFile(new URL(file,import.meta.url),'utf8')).toString('base64')}`);
const {findPlaces,parseHash,seatKey}=await load('../site/js/query.js');
const {contains}=await load('../site/js/geo.js');
const {isMarket}=await load('../site/js/calendar.js');
const entries=[{k:'大桥镇',sub:'广西 · 宾阳县'},{k:'大桥镇',sub:'四川 · 南部县'},{k:'东城区',sub:'北京'}];
assert.equal(findPlaces(entries,' ').length,0);
assert.equal(findPlaces(entries,'大桥镇').length,2);
assert.equal(findPlaces(entries,'大桥镇（宾阳县）')[0].sub,'广西 · 宾阳县');
assert.equal(findPlaces(entries,'宾阳县大桥镇').length,1);
const state=parseHash('#108.8990,23.1750,20?date=2026-10-13&seat=450126%3A%E5%A4%A7%E6%A1%A5%E9%95%87');
assert.deepEqual(state.ll,[108.899,23.175]);assert.equal(state.date,'2026-10-13');assert.equal(state.seat,'450126:大桥镇');
assert.equal(parseHash('#NaN,0,20').ll,null);
assert.equal(parseHash('#ledger').ll,null);
assert.deepEqual(parseHash('#region,county,450126,108.9,23.1,30').region,{level:'county',id:450126});
assert.equal(seatKey({c:0,t:'大桥镇'},[[450126]]),'450126:大桥镇');
const polygon={type:'Polygon',coordinates:[[[0,0],[4,0],[4,4],[0,4],[0,0]],[[1,1],[2,1],[2,2],[1,2],[1,1]]]};
assert.equal(contains(polygon,[3,3]),true);assert.equal(contains(polygon,[1.5,1.5]),false);assert.equal(contains(polygon,[5,3]),false);
assert.equal(isMarket({type:'solar_days',days:[12]}, {d:'2026-10-12'}),true);
assert.equal(isMarket({type:'solar_days',days:[12]}, {d:'2026-10-13'}),false);
console.log('Search ambiguity, empty input, stable shared state and administrative containment passed.');
